// Embeds the Playbook (content/ plus GLOSSARY.md) and its edition hash into the API (ADR 0005).
// Run by `mise run generate`; `mise run check` fails when the output is stale.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const out = join(root, "apps/api/src/playbook.generated.ts");

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const paths = [...walk(join(root, "content")), join(root, "GLOSSARY.md")]
  .map((p) => relative(root, p).split("\\").join("/"))
  .sort();

const files: Record<string, string> = {};
const hash = createHash("sha256");
for (const path of paths) {
  const text = readFileSync(join(root, path), "utf-8");
  files[path] = text;
  hash.update(path).update("\0").update(text).update("\0");
}

writeFileSync(
  out,
  `// Generated by scripts/gen-playbook.ts from content/ and GLOSSARY.md. Do not edit.
/** Playbook edition: sha256 of the sorted paths and contents. */
export const PLAYBOOK_EDITION = ${JSON.stringify(hash.digest("hex"))};

export const PLAYBOOK_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};
`,
);
